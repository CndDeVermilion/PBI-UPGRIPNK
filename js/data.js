async function loadDynamicData() {
  try {
    const res = await fetch('api/api.php?action=get');
    if (res.ok) {
      const data = await res.json();
      if (data.prodiInfo) prodiInfo = data.prodiInfo;
      if (data.dosenList) dosenList = data.dosenList;
      if (data.kurikulumData) kurikulumData = data.kurikulumData;
      if (data.beritaList) beritaList = data.beritaList;
      if (data.testimoniAlumni) testimoniAlumni = data.testimoniAlumni;
      if (data.fasilitasData) fasilitasData = data.fasilitasData;
      if (data.risetData) risetData = data.risetData;

      if (typeof renderHomepage === 'function') renderHomepage();
      if (typeof renderProfil === 'function') renderProfil();
      if (typeof renderAkademik === 'function') renderAkademik();
      if (typeof renderFasilitas === 'function') renderFasilitas();
      if (typeof renderKemahasiswaan === 'function') renderKemahasiswaan();
      if (typeof renderPenelitian === 'function') renderPenelitian();
      if (typeof renderKontak === 'function') renderKontak();
    }
  } catch (err) {
    console.log('Menggunakan data bawaan js/data.js:', err);
  }
}

